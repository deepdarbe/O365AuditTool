    Write-Host "    Push-Location '$quotedDir'; $runCommand; Pop-Location" -ForegroundColor Yellow
    Write-Host "Uygulama appsettings.Production.json dosyasini calisma dizininden okur; Push-Location zorunludur." -ForegroundColor DarkYellow

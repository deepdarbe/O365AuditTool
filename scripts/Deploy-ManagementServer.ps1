    return $Certificate.Subject.Equals($Certificate.Issuer, [StringComparison]::OrdinalIgnoreCase)
}

function Test-CertificateChainTrust {
    param([Parameter(Mandatory)]$Certificate)

    # Program.cs resolves the TLS certificate with X509Store.Find(..., validOnly: $true). The Windows store
    # search suppresses revocation checking, so revocation is disabled here too: on an MSP domain controller
    # with no outbound internet an AD CS certificate whose CRL endpoint is unreachable would otherwise be
    # reported as untrusted even though the service loads it happily.
    $chain = New-Object Security.Cryptography.X509Certificates.X509Chain
    $chain.ChainPolicy.RevocationMode = [Security.Cryptography.X509Certificates.X509RevocationMode]::NoCheck
    try {
        $built = $chain.Build($Certificate)
        $statusFlags = @($chain.ChainStatus | ForEach-Object { [string]$_.Status } | Select-Object -Unique)
        return @{
            Trusted = [bool]$built
            Status = $statusFlags
        }
    }
    finally {
        if ($chain -is [IDisposable]) {
            $chain.Dispose()
        }
    }
}

function Import-TrustedRootCertificate {
    param([Parameter(Mandatory)]$Certificate)

    # RawData is the DER encoding of the certificate alone, so the private key stays in LocalMachine\My.
    $publicCertificate = New-Object `
        -TypeName Security.Cryptography.X509Certificates.X509Certificate2 `
        -ArgumentList (, $Certificate.RawData)
    $rootStore = New-Object `
        -TypeName Security.Cryptography.X509Certificates.X509Store `
        -ArgumentList @('Root', [Security.Cryptography.X509Certificates.StoreLocation]::LocalMachine)
    try {
        $rootStore.Open([Security.Cryptography.X509Certificates.OpenFlags]::ReadWrite)
        $rootStore.Add($publicCertificate)
    }
    finally {
        $rootStore.Close()
        if ($publicCertificate -is [IDisposable]) {
            $publicCertificate.Dispose()
        }
    }
}

function Ensure-SelfSignedCertificateTrust {
    param(
        [Parameter(Mandatory)]$Certificate,
        [Parameter(Mandatory)][bool]$TrustAllowed
    )

    $thumbprint = [string]$Certificate.Thumbprint
    $chainResult = Test-CertificateChainTrust -Certificate $Certificate
    if ($chainResult.Trusted) {
        return
    }

    if (-not (Test-SelfSignedCertificate -Certificate $Certificate)) {
        Write-Warning ("TLS sertifika zinciri dogrulanamadi: $thumbprint (durum: $($chainResult.Status -join ', ')). " +
                       "Sertifika bir CA tarafindan verilmis; kok ve ara CA sertifikalarini LocalMachine\Root ve " +
                       "LocalMachine\CA depolarina siz dagitmalisiniz. Baskasina ait sertifika otomatik guvenilir yapilmaz.")
        return
    }

    $basicConstraints = $Certificate.Extensions | Where-Object { $_.Oid.Value -eq '2.5.29.19' } | Select-Object -First 1
    if ($basicConstraints -and $basicConstraints.CertificateAuthority) {
        # A leaf certificate in Root can only vouch for itself. A CA=true certificate in Root becomes a
        # machine-wide issuing authority for ANY hostname on a domain controller, which is an unbounded
        # trust delegation and never something a deployment should grant on its own.
        throw ("TLS sertifikasi CA (basicConstraints CA=true) olarak isaretli: $thumbprint. Bu sertifika " +
               "LocalMachine\Root deposuna otomatik eklenmez; makine genelinde sinirsiz guven delegasyonu olur. " +
               "Yalnizca sunucu (leaf) sertifikasi kullanin veya guveni bilincli olarak siz dagitin.")
    }

    if (-not $TrustAllowed) {
        Write-Warning ("Self-signed TLS sertifikasi LocalMachine\Root deposunda degil: $thumbprint " +
                       "(durum: $($chainResult.Status -join ', ')). Sertifika bu script tarafindan uretilmedigi ve " +
                       "-TlsCertificateThumbprint ile acikca secilmedigi icin otomatik guvenilir yapilmadi. " +
                       "Bilincli olarak kullanacaksaniz '-TlsCertificateThumbprint $thumbprint' ile calistirin.")
        return
    }

    # BURCUDC: the self-signed certificate had been imported into LocalMachine\CA (intermediate) and never
    # into Root, so the chain stayed UntrustedRoot, the validOnly lookup in Program.cs found nothing and the
    # service threw on startup. Only the public part is imported and only for certificates this script owns.
    try {
        Import-TrustedRootCertificate -Certificate $Certificate
        Write-Host "Self-signed TLS sertifikasinin public bolumu LocalMachine\Root deposuna eklendi: $thumbprint" -ForegroundColor DarkCyan
    }
    catch {
        Write-Warning "Self-signed TLS sertifikasi LocalMachine\Root deposuna eklenemedi: $thumbprint. $($_.Exception.Message)"
    }

    $verifiedChain = Test-CertificateChainTrust -Certificate $Certificate
    if ($verifiedChain.Trusted) {
        Write-Host "TLS sertifika zinciri dogrulandi: $thumbprint" -ForegroundColor DarkCyan
        return
    }

    Write-Warning ("TLS sertifika zinciri Root importundan sonra da dogrulanamadi: $thumbprint " +
                   "(durum: $($verifiedChain.Status -join ', ')). Servis sertifikayi yalnizca gecerli zincir ile " +
                   "arar, bu haliyle baslatilamaz. 'Get-ChildItem Cert:\LocalMachine\Root\$thumbprint' ile " +
                   "sertifikanin Root deposunda oldugunu dogrulayin; sertifika yalnizca LocalMachine\CA icinde " +
                   "duruyorsa zincir UntrustedRoot kalir.")
}

function Remove-DeploymentDirectory {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][string]$Root
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Container)) {
        return
    }

    $resolvedRoot = [IO.Path]::GetFullPath($Root).TrimEnd('\') + '\'
    $resolvedPath = [IO.Path]::GetFullPath($Path)
    $leaf = Split-Path $resolvedPath -Leaf
    if (
        -not $resolvedPath.StartsWith($resolvedRoot, [StringComparison]::OrdinalIgnoreCase) -or
        $leaf -notmatch '^\.(?:staging|rollback|failed)-[0-9a-f]{32}$'
    ) {
        throw "Guvenli olmayan deployment cleanup path'i reddedildi: '$resolvedPath'."
    }

    Remove-Item -LiteralPath $resolvedPath -Recurse -Force
}

function Resolve-TlsCertificateThumbprint {
    param(
        [string]$Thumbprint,
        [bool]$AllowInsecure,
        [string]$DnsName,
        [bool]$AutoConfigure
    )

    if ($AllowInsecure) {
        Write-Warning 'Dashboard HTTP istisnasi etkin. Bu mod yalnizca izole test aginda kullanilmalidir.'
        return ''
    }
    $operatorSelectedCertificate = $script:TlsThumbprintExplicitlySupplied
    $scriptManagedCertificate = $false
    if ([string]::IsNullOrWhiteSpace($Thumbprint) -and $AutoConfigure) {
        $certificate = Get-ChildItem -Path 'Cert:\LocalMachine\My' -ErrorAction SilentlyContinue |
            Where-Object { Test-TlsCertificateCandidate -Certificate $_ -DnsName $DnsName } |
            Sort-Object NotAfter -Descending |
            Select-Object -First 1
        if ($null -eq $certificate) {
            $certificate = New-AutomaticTlsCertificate -DnsName $DnsName
            $scriptManagedCertificate = $true
        }
        elseif ([string]$certificate.FriendlyName -eq $automaticTlsCertificateFriendlyName) {
            $scriptManagedCertificate = $true
        }
        if ($null -eq $certificate -or [string]::IsNullOrWhiteSpace([string]$certificate.Thumbprint)) {
            throw "DashboardDnsName '$DnsName' icin otomatik TLS sertifikasi olusturulamadi."
        }

        $Thumbprint = [string]$certificate.Thumbprint
        Write-Host "TLS sertifikasi otomatik secildi: $Thumbprint" -ForegroundColor DarkCyan
    }
    elseif ([string]::IsNullOrWhiteSpace($Thumbprint)) {
        throw 'Production dashboard icin -TlsCertificateThumbprint zorunludur. Otomatik secim icin -AutoConfigure, yalnizca izole test icin -AllowInsecureHttpDashboard kullanilabilir.'
    }

    $normalized = ($Thumbprint -replace '\s', '').ToUpperInvariant()
    if ($normalized -notmatch '^[0-9A-F]{40,128}$') {
        throw 'TlsCertificateThumbprint gecerli hexadecimal sertifika thumbprint degerinde degil.'
    }

    $certificate = Get-Item -LiteralPath "Cert:\LocalMachine\My\$normalized" -ErrorAction SilentlyContinue
    if ($null -eq $certificate -or -not $certificate.HasPrivateKey) {
        throw "LocalMachine\\My deposunda private key iceren TLS sertifikasi bulunamadi: '$normalized'."
    }
    if ($certificate.NotAfter.ToUniversalTime() -le [DateTime]::UtcNow) {
        throw "TLS sertifikasinin suresi dolmus: '$normalized'."
    }
    if ($certificate.NotBefore.ToUniversalTime() -gt [DateTime]::UtcNow) {
        throw "TLS sertifikasi henuz gecerli degil: '$normalized'."
    }

    if (-not (Test-TlsCertificateCandidate -Certificate $certificate -DnsName $DnsName)) {
        $certificateDnsNames = @(Get-CertificateDnsNames -Certificate $certificate)
        throw "TLS sertifikasi private key, tarih, Server Authentication EKU veya DashboardDnsName '$DnsName' gereksinimini karsilamiyor. Sertifika adlari: $($certificateDnsNames -join ', ')."
    }

    Ensure-SelfSignedCertificateTrust `
        -Certificate $certificate `
        -TrustAllowed ($scriptManagedCertificate -or $operatorSelectedCertificate)

    return $normalized
}

function Ensure-HttpSpns {
    param(
        [Parameter(Mandatory)][string]$AccountName,
        [Parameter(Mandatory)][string]$DnsName
    )

    $setSpnPath = Join-Path $env:SystemRoot 'System32\setspn.exe'
    if (-not (Test-Path -LiteralPath $setSpnPath -PathType Leaf)) {
        throw "setspn.exe bulunamadi; Kerberos HTTP SPN dogrulanamiyor."
    }

    $names = @($DnsName, $DnsName.Split('.')[0]) |
        Where-Object { -not [string]::IsNullOrWhiteSpace($_) } |
        Select-Object -Unique
    foreach ($name in $names) {
        $spn = "HTTP/$name"
        $existingForAccount = @(& $setSpnPath -L $AccountName 2>&1)
        if ($LASTEXITCODE -eq 0 -and ($existingForAccount | Where-Object { $_.Trim().Equals($spn, [StringComparison]::OrdinalIgnoreCase) })) {
            continue
        }

        $result = @(& $setSpnPath -S $spn $AccountName 2>&1)
        if ($LASTEXITCODE -ne 0) {
            # Changing the service identity leaves the HTTP SPN on the previous account, so
            # setspn -S refuses as a duplicate. Migrate it only when this machine's own
            # computer account holds it -- that is the registration our own LocalSystem
            # deployment created. Any other holder is someone else's and is never touched.
            $ownComputerAccount = "$env:COMPUTERNAME`$"
            $holderLines = @(& $setSpnPath -Q $spn 2>&1)
            $holder = $holderLines |
                Where-Object { $_ -match '^\s*CN=' } |
                Select-Object -First 1
            $heldByThisComputer = $holderLines |
                Where-Object { $_ -match ("^\s*CN=" + [regex]::Escape($env:COMPUTERNAME) + ",") }

            if ($heldByThisComputer -and -not $AccountName.TrimEnd('$').Equals($env:COMPUTERNAME, [StringComparison]::OrdinalIgnoreCase)) {
                Write-Warning "SPN '$spn' bu sunucunun bilgisayar hesabinda kayitli; servis kimligi degistigi icin '$ownComputerAccount' uzerinden kaldirilip '$AccountName' hesabina tasiniyor."
                $removal = @(& $setSpnPath -D $spn $ownComputerAccount 2>&1)
                if ($LASTEXITCODE -ne 0) {
                    throw "SPN '$spn' eski hesaptan kaldirilamadi: setspn -D $spn $ownComputerAccount. Cikti: $($removal -join ' ')."
                }

                $result = @(& $setSpnPath -S $spn $AccountName 2>&1)
                if ($LASTEXITCODE -ne 0) {
                    throw "Kerberos SPN kaydedilemedi: setspn -S $spn $AccountName. Cikti: $($result -join ' ')."
                }
                continue
            }

            throw ("Kerberos SPN kaydedilemedi: setspn -S $spn $AccountName. SPN su anda '" +
                   ($(if ($holder) { $holder.Trim() } else { 'bilinmeyen bir hesap' })) +
                   "' uzerinde kayitli. Baska bir hesaba ait SPN otomatik tasinmaz; dogruysa once " +
                   "'setspn -D $spn <mevcut-hesap>' ile kaldirin. Cikti: $($result -join ' ')")
        }
    }
}

function Grant-TlsPrivateKeyRead {
    param(
        [Parameter(Mandatory)][string]$Thumbprint,
        [Parameter(Mandatory)][Security.Principal.SecurityIdentifier]$AccountSid
    )

    $certificate = Get-Item -LiteralPath "Cert:\LocalMachine\My\$Thumbprint" -ErrorAction Stop
    $key = $null
    $keyPath = $null
    try {
        $key = [Security.Cryptography.X509Certificates.RSACertificateExtensions]::GetRSAPrivateKey($certificate)
        if ($null -eq $key) {
            $key = [Security.Cryptography.X509Certificates.ECDsaCertificateExtensions]::GetECDsaPrivateKey($certificate)
        }

        if ($key -is [Security.Cryptography.RSACng] -or $key -is [Security.Cryptography.ECDsaCng]) {
            $keyPath = Join-Path $env:ProgramData "Microsoft\Crypto\Keys\$($key.Key.UniqueName)"
        }
        elseif ($key -is [Security.Cryptography.RSACryptoServiceProvider]) {
            $containerName = $key.CspKeyContainerInfo.UniqueKeyContainerName
            $keyPath = Join-Path $env:ProgramData "Microsoft\Crypto\RSA\MachineKeys\$containerName"
        }

        if ([string]::IsNullOrWhiteSpace($keyPath) -or -not (Test-Path -LiteralPath $keyPath -PathType Leaf)) {
            throw "TLS private key dosyasi cozumlenemedi. Sertifikanin machine-key olarak import edildigini dogrulayin: '$Thumbprint'."
        }

        $keyAcl = Get-Acl -LiteralPath $keyPath
        $rule = New-Object Security.AccessControl.FileSystemAccessRule(
            $AccountSid,
            [Security.AccessControl.FileSystemRights]::Read,
            [Security.AccessControl.AccessControlType]::Allow)
        $keyAcl.SetAccessRule($rule)
        Set-Acl -LiteralPath $keyPath -AclObject $keyAcl
    }
    finally {
        if ($key -is [IDisposable]) {
            $key.Dispose()
        }
    }
}

function Ensure-TlsPrivateKeyAccess {
    param(
        [Parameter(Mandatory)][string]$Thumbprint,
        [Parameter(Mandatory)][hashtable]$Identity
    )

    if ($Identity.Type -eq 'LocalSystem') {
        if ($null -eq $Identity.AclSid -or $Identity.AclSid.Value -ne 'S-1-5-18') {
            throw 'LocalSystem servis kimligi beklenen S-1-5-18 SID degerine sahip degil.'
        }

        # Machine certificate keys grant SYSTEM access by default; provider-specific file ACL lookup is unnecessary.
        Write-Verbose "LocalSystem TLS private key erisimi machine-key varsayilan ACL'i ile saglanacak."
        return
    }

    Grant-TlsPrivateKeyRead -Thumbprint $Thumbprint -AccountSid $Identity.AclSid
}

function Resolve-DotNetPath {
    param([bool]$Publishing)

    $candidates = @()
    $command = Get-Command dotnet -ErrorAction SilentlyContinue
    if ($command -and (Test-Path -LiteralPath $command.Source -PathType Leaf)) {
        $candidates += $command.Source
    }

    $candidates += @(
        $(if (-not [string]::IsNullOrWhiteSpace($env:USERPROFILE)) { Join-Path $env:USERPROFILE '.dotnet\dotnet.exe' }),
        (Join-Path $env:ProgramFiles 'dotnet\dotnet.exe'),
        'C:\Program Files\dotnet\dotnet.exe'
    ) | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Select-Object -Unique

    foreach ($candidate in ($candidates | Select-Object -Unique)) {
        if (-not (Test-Path -LiteralPath $candidate -PathType Leaf)) {
            continue
        }

        if ($Publishing) {
            $sdks = @(& $candidate --list-sdks 2>$null)
            if ($LASTEXITCODE -eq 0 -and ($sdks -match '^10\.\d+\.\d+')) {
                return $candidate
            }
        }
        else {
            $runtimes = @(& $candidate --list-runtimes 2>$null)
            if ($LASTEXITCODE -eq 0 -and ($runtimes -match '^Microsoft\.ASPNetCore\.App 10\.')) {
                return $candidate
            }
        }
    }

    $requirement = if ($Publishing) { '.NET 10 SDK' } else { 'ASP.NET Core Runtime 10' }
    throw "$requirement bulunamadi. PATH, %USERPROFILE%\.dotnet ve Program Files konumlari kontrol edildi."
}

function Assert-DotNet10 {
    param(
        [string]$DotNetPath,
        [bool]$Publishing
    )

    & $DotNetPath --info *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "dotnet calistirilamadi: '$DotNetPath'."
    }

    if ($Publishing) {
        $sdks = @(& $DotNetPath --list-sdks 2>$null)
        if (-not ($sdks -match '^10\.\d+\.\d+')) {
            throw ".NET 10 SDK bulunamadi. Kaynak koddan publish icin Microsoft.DotNet.SDK.10 kurulmalidir."
        }
    }

    $runtimes = @(& $DotNetPath --list-runtimes 2>$null)
    if (-not ($runtimes -match '^Microsoft\.ASPNetCore\.App 10\.')) {
        throw "ASP.NET Core Runtime 10 bulunamadi. Framework-dependent servisi calistirmak icin gereklidir."
    }
}

function Assert-PsExec {
    param(
        [string]$Path,
        [bool]$AllowUnsigned
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "PsExec bulunamadi: '$Path'. Sysinternals PsExec'i bu konuma kopyalayin veya -PsExecPath belirtin."
    }

    if ([IO.Path]::GetExtension($Path) -ne '.exe') {
        throw "PsExecPath bir .exe dosyasi gostermelidir: '$Path'."
    }

    $signature = Get-AuthenticodeSignature -LiteralPath $Path
    if ($signature.Status -ne [System.Management.Automation.SignatureStatus]::Valid -and -not $AllowUnsigned) {
        throw "PsExec imzasi gecerli degil (durum: $($signature.Status)). Dogru Sysinternals binary'sini kullanin. Bilincli istisna icin -AllowUnsignedPsExec gerekir."
    }
    if (-not $AllowUnsigned -and $signature.SignerCertificate.Subject -notmatch '(^|,\s*)CN=Microsoft Corporation(,|$)') {
        throw "PsExec Microsoft Corporation tarafindan imzalanmamis. Resmi Sysinternals binary'sini kullanin."
    }
}

